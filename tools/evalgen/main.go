// Command evalgen writes the synthetic evaluation dataset used by the
// estimator's baseline backtest (test/fixtures/eval/dataset.json).
//
// The dataset is SYNTHETIC. It is generated from a fixed seed with a simple
// price model (base price x city factor x shop factor x noise, plus a few
// outliers). The backtest therefore measures whether the estimator recovers
// prices under that model and stays calibrated; it says nothing about
// real-world accuracy in Bangladesh. See docs/estimation.md.
//
// Usage: cd tools && go run ./evalgen > ../test/fixtures/eval/dataset.json
package main

import (
	"encoding/json"
	"math"
	"math/rand/v2"
	"os"
)

type product struct {
	ID         int64  `json:"id"`
	CategoryID int64  `json:"category_id"`
	Name       string `json:"name"`
	Unit       string `json:"unit"`
	Quantity   int64  `json:"quantity"`
	base       int64
}

type shop struct {
	ID       int64   `json:"id"`
	Lat      float64 `json:"lat"`
	Lng      float64 `json:"lng"`
	Division string  `json:"division"`
	factor   float64
	city     float64
}

type listing struct {
	ID          int64   `json:"id"`
	ShopID      int64   `json:"shop_id"`
	ProductID   int64   `json:"product_id"`
	PricePoisha int64   `json:"price_poisha"`
	AgeDays     float64 `json:"age_days"`
}

type offer struct {
	ID          int64   `json:"id"`
	ProductID   int64   `json:"product_id"`
	PricePoisha int64   `json:"price_poisha"`
	AgeDays     float64 `json:"age_days"`
}

func main() {
	rng := rand.New(rand.NewPCG(2026, 1110)) //nolint:gosec // deterministic fixture generation
	products := []product{
		{1, 1, "Rice A 5 kg", "g", 5000, 400}, {2, 1, "Rice A 1 kg", "g", 1000, 82}, {3, 1, "Rice B 5 kg", "g", 5000, 450},
		{4, 1, "Flour 2 kg", "g", 2000, 130}, {5, 2, "Lentil A 1 kg", "g", 1000, 140}, {6, 2, "Lentil B 1 kg", "g", 1000, 180},
		{7, 3, "Oil A 1 L", "ml", 1000, 175}, {8, 3, "Oil A 5 L", "ml", 5000, 850}, {9, 3, "Oil B 1 L", "ml", 1000, 280},
		{10, 4, "Sugar 1 kg", "g", 1000, 135}, {11, 4, "Salt 1 kg", "g", 1000, 42}, {12, 5, "Egg 12 pcs", "pc", 12, 150},
	}
	cities := []struct {
		division string
		lat, lng float64
		factor   float64
	}{
		{"Chattogram", 22.335109, 91.834073, 1.00},
		{"Dhaka", 23.7115253, 90.4111451, 1.05},
	}
	var shops []shop
	for _, c := range cities {
		for range 40 {
			// Roughly 4 km standard deviation around the centre.
			shops = append(shops, shop{
				ID: int64(len(shops) + 1), Division: c.division,
				Lat: c.lat + rng.NormFloat64()*0.036, Lng: c.lng + rng.NormFloat64()*0.039,
				factor: 1 + rng.NormFloat64()*0.04, city: c.factor,
			})
		}
	}
	var listings []listing
	for _, s := range shops {
		for _, p := range products {
			if rng.Float64() > 0.6 {
				continue
			}
			price := float64(p.base) * s.city * s.factor * (1 + rng.NormFloat64()*0.03)
			if rng.Float64() < 0.03 {
				price *= 1.5 // an occasional outlier, as real data has
			}
			listings = append(listings, listing{
				ID: int64(len(listings) + 1), ShopID: s.ID, ProductID: p.ID,
				PricePoisha: int64(math.Round(price)) * 100, AgeDays: math.Round(rng.Float64()*200) / 10,
			})
		}
	}
	var offers []offer
	for _, p := range products {
		for range 2 + rng.IntN(2) {
			price := float64(p.base) * 1.08 * (1 + rng.NormFloat64()*0.03)
			offers = append(offers, offer{
				ID: int64(len(offers) + 1), ProductID: p.ID,
				PricePoisha: int64(math.Round(price)) * 100, AgeDays: math.Round(rng.Float64()*50) / 10,
			})
		}
	}
	enc := json.NewEncoder(os.Stdout)
	if err := enc.Encode(map[string]any{
		"description": "SYNTHETIC evaluation dataset generated by tools/evalgen from a fixed seed. Prices follow a simple model and are not market data.",
		"products":    products, "shops": shops, "listings": listings, "offers": offers,
	}); err != nil {
		os.Exit(1)
	}
}
